"""Write the country table in reference/methods-by-country.md from data/country_tiers.csv.

Usage:
    python figures/scripts/methods_by_country.py

The table is written between the BEGIN and END markers in the page; everything
else on the page is left as it is. Rows keep the CSV's order (by country name).
"""

from __future__ import annotations

import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TIERS_CSV = os.path.join(ROOT, "data", "country_tiers.csv")
PAGE = os.path.join(ROOT, "reference", "methods-by-country.md")
BEGIN = "<!-- BEGIN country-table: generated by figures/scripts/methods_by_country.py -->"
END = "<!-- END country-table -->"

HEADER = (
    "| Country | ISO3 | Tier | IO table | IO data year | GHG data | GHG data year |\n"
    "|---|---|---|---|---|---|---|\n"
)


def build_table() -> str:
    with open(TIERS_CSV, encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    lines = [
        f"| {r['country']} | {r['iso3']} | {r['tier']} | {r['io_source']} "
        f"| {r['io_year']} | {r['ghg_source']} | {r['ghg_year']} |"
        for r in rows
    ]
    return HEADER + "\n".join(lines) + "\n"


def main() -> None:
    with open(PAGE, encoding="utf-8") as f:
        page = f.read()
    start = page.index(BEGIN) + len(BEGIN)
    stop = page.index(END)
    page = page[:start] + "\n\n" + build_table() + "\n" + page[stop:]
    with open(PAGE, "w", encoding="utf-8", newline="\n") as f:
        f.write(page)


if __name__ == "__main__":
    main()
